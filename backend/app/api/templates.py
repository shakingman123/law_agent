def _extract_placeholders(content: str) -> list[str]:
    """按首次出现顺序提取 {{占位符}}，忽略自动填充的 date。"""
    seen: list[str] = []
    for match in re.finditer(r"\{\{([^{}]+)\}\}", content):
        name = match.group(1).strip()
        if name and name != "date" and name not in seen:
            seen.append(name)
    return seen


