def seed_templates(db: Session) -> None:
    """启动时幂等播种/更新公共模板：新增缺失项、同步正文、清理已下架项。"""
    seed_names = {t["name"] for t in SEED_TEMPLATES}
    existing = db.query(DocumentTemplate).filter_by(scope="public").all()
    by_name = {t.name: t for t in existing}

    for tpl in existing:
        if tpl.name not in seed_names:
            db.delete(tpl)

    for spec in SEED_TEMPLATES:
        tpl = by_name.get(spec["name"])
        if tpl is None:
            tpl = DocumentTemplate(scope="public")
            by_name[spec["name"]] = tpl
        tpl.name = spec["name"]
        tpl.doc_type = spec["doc_type"]
        tpl.content = spec["content"]
        tpl.placeholders = _extract_placeholders(spec["content"])
        db.add(tpl)

    db.commit()


@router.get("", response_model=list[TemplateOut])
def list_templates(
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """列出当前用户可见模板：公共 + 本人私有。"""
    return (
        db.query(DocumentTemplate)
        .filter(
            (DocumentTemplate.scope == "public")
            | (DocumentTemplate.user_id == user.id)
        )
        .order_by(DocumentTemplate.scope, DocumentTemplate.id)
        .all()
    )


@router.post("", response_model=TemplateOut)
def create_template(
    payload: TemplateCreate,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    """新建私有模板。"""
    tpl = DocumentTemplate(
        name=payload.name,
        doc_type=payload.doc_type,
        content=payload.content,
        placeholders=payload.placeholders,
        scope="private",
        user_id=user.id,
    )
    db.add(tpl)
    db.commit()
    db.refresh(tpl)
    return tpl


@router.delete("/{template_id}")
def delete_template(
    template_id: int,
    user: User = Depends(get_current_user),
    db: Session = Depends(get_db),
):
    tpl = db.get(DocumentTemplate, template_id)
    if not tpl:
        raise HTTPException(status_code=404, detail="模板不存在")
    if tpl.scope == "public" and not user.is_admin:
        raise HTTPException(status_code=403, detail="公共模板仅管理员可删除")
    if tpl.scope == "private" and tpl.user_id != user.id:
        raise HTTPException(status_code=403, detail="无权删除他人模板")
    db.delete(tpl)
    db.commit()
    return {"ok": True}


class ExtractResult(BaseModel):
    text: str
    file_name: str
    char_count: int


@router.post("/extract", response_model=ExtractResult)
def extract_file(
    file: UploadFile = File(...),
    user: User = Depends(get_current_user),
):
    """上传 PDF/Word/TXT 文件，提取纯文本用于模板内容。

    复用 RAG 模块的文本提取能力（pdfplumber/python-docx）。
    """
    suffix = os.path.splitext(file.filename or "")[1].lower()
    if suffix not in (".txt", ".md", ".markdown", ".pdf", ".docx"):
        raise HTTPException(
            status_code=400,
            detail="仅支持 .txt/.md/.pdf/.docx 格式",
        )
    with tempfile.NamedTemporaryFile(delete=False, suffix=suffix) as tmp:
        tmp.write(file.file.read())
        tmp_path = tmp.name
    try:
        text = _extract_text(tmp_path)
    finally:
        os.unlink(tmp_path)
    if not text or not text.strip():
        raise HTTPException(status_code=422, detail="文件无可提取文本")
    return ExtractResult(
        text=text,
        file_name=file.filename or "",
        char_count=len(text),
    )
